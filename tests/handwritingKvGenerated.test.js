import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, mkdir, writeFile, readFile, access, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve, dirname, basename} from 'node:path';
import {preserveGeneratedClient} from '../scripts/handwriting-kv-generated.js';

async function removeOwned(directory) {
  assert.equal(dirname(resolve(directory)), resolve(tmpdir()));
  assert.match(basename(directory), /^handwriting-kv-generated-test-/);
  await rm(directory, {recursive: true});
}

test('KV harness restores original generated bytes and removes only its added files', async () => {
  const owned = await mkdtemp(join(tmpdir(), 'handwriting-kv-generated-test-'));
  try {
    const root = join(owned, 'client'); await mkdir(root);
    await writeFile(join(root, 'client.ts'), 'pre-existing dirty\r\n');
    await writeFile(join(root, 'custom.ts'), 'pre-existing untracked\n');
    const saved = await preserveGeneratedClient(root, join(owned, 'backup'));
    await writeFile(join(root, 'client.ts'), 'regenerated\n');
    await writeFile(join(root, 'new.ts'), 'new generated model');
    await saved.recordGenerated(); await saved.restore();
    assert.equal(await readFile(join(root, 'client.ts'), 'utf8'), 'pre-existing dirty\r\n');
    assert.equal(await readFile(join(root, 'custom.ts'), 'utf8'), 'pre-existing untracked\n');
    await assert.rejects(access(join(root, 'new.ts')), {code: 'ENOENT'});
  } finally { await removeOwned(owned); }
});

test('KV harness preserves concurrent edits and a recovery backup', async () => {
  const owned = await mkdtemp(join(tmpdir(), 'handwriting-kv-generated-test-'));
  try {
    const root = join(owned, 'client'), backup = join(owned, 'backup'); await mkdir(root);
    await writeFile(join(root, 'client.ts'), 'before');
    const saved = await preserveGeneratedClient(root, backup);
    await writeFile(join(root, 'client.ts'), 'generated'); await saved.recordGenerated();
    await writeFile(join(root, 'client.ts'), 'concurrent edit');
    await assert.rejects(saved.restore(), /changed concurrently/);
    assert.equal(await readFile(join(root, 'client.ts'), 'utf8'), 'concurrent edit');
    assert.equal(await readFile(join(backup, 'client.ts'), 'utf8'), 'before');
  } finally { await removeOwned(owned); }
});
